import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { root } from './local-config.mjs';

/**
 * Writes the list of migrations this build ships with, as source the
 * application can import.
 *
 * The application needs to know which migrations it expects so it can refuse
 * to serve a database that does not match. It cannot read the .sql directory
 * at runtime: the web build bundles this package, and a directory read is not
 * statically resolvable. Generating a manifest keeps the check available in
 * every environment without shipping the SQL to the browser build.
 */
const directory = root + 'packages/database/migrations/';
const target = root + 'packages/database/src/migration-manifest.ts';

export function buildManifest() {
  const entries = readdirSync(directory)
    .filter((name) => name.endsWith('.sql'))
    .sort()
    .map((name) => ({
      name,
      checksum: createHash('sha256')
        .update(readFileSync(directory + name, 'utf8'))
        .digest('hex'),
    }));
  return `// Generated by scripts/migration-manifest.mjs. Do not edit.
// Regenerate with: pnpm migrations:manifest
export const migrationManifest: { name: string; checksum: string }[] = [
${entries.map((e) => `  { name: '${e.name}', checksum: '${e.checksum}' },`).join('\n')}
];
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const content = buildManifest();
  if (process.argv.includes('--check')) {
    const current = readFileSync(target, 'utf8');
    if (current !== content) {
      console.error(
        'The migration manifest is out of date. Run pnpm migrations:manifest and commit the result.',
      );
      process.exit(1);
    }
    console.log('Migration manifest matches the migrations on disk.');
  } else {
    writeFileSync(target, content);
    console.log('Migration manifest written.');
  }
}
